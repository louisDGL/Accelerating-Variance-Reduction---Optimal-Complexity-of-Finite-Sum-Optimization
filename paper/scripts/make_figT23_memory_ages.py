sys.path.insert(0, es.ROOT)
from vrlab.algorithms import _index_stream  # noqa: E402  (the index streams of vrlab.algorithms.saga)

NAME = "figT23_memory_ages"
N_A, PASSES_A, SEED_A = 30, 4, 0       # panel (a): size of the small table, passes drawn, seed of the two streams
N, B = 1000, 1                         # panel (b)
U_MAX = 7.0                            # panel (b): ages up to U_MAX passes
P_MAX = 5                              # passes of the count of the initial entries (printed)
MARK_W = 1.5                           # panel (a): width of a mark, in iterations
SIM_PASSES, SIM_BURN, SIM_SEED = 4000, 40, 1    # check of the laws on the index streams (stationary window)
TOL_SIM = 4e-3                         # largest accepted |simulated - exact| of P(age > u) and of the shares


# ----------------------------------------------------------------------------------------------------------------------
# data
# ----------------------------------------------------------------------------------------------------------------------
def stream(n, passes, order, seed):
    """The first passes * n indices of vrlab.algorithms.saga(..., seed=seed, sampling=order), batch one."""
    return np.concatenate(list(_index_stream(np.random.default_rng(seed), n, passes * n, sampling=order)))


def age_survival(n, order, ages):
    """Exact P(age > a) at batch one for integer ages a (iterations); see the docstring for the definition."""
    a = np.asarray(ages, dtype=np.int64)
    if order == "iid":
        return (1.0 - 1.0 / n) ** a
    if order == "cyclic":
        return np.clip(n - a, 0, n) / n
    if order == "rr":
        r = np.arange(n)[:, None]
        same = np.clip(r - a[None, :], 0, None) / n
        previous = (n - r) / n * np.clip(n + r - a[None, :], 0, n) / n
        return (same + previous).mean(axis=0)
    raise ValueError(order)


def rr_limit(u):
    """Limit n -> infinity of the permutation law, u in passes."""
    u = np.asarray(u, dtype=float)
    return np.where(u <= 1.0, 1.0 - u + u ** 3 / 6.0, np.clip(2.0 - u, 0.0, None) ** 3 / 6.0)


def rr_enumeration(n):
    """P(age > a), a = 0..2n, by enumerating the position r of the iteration in its pass and the positions of the
    entry in that pass and in the previous one (n^3 equally likely cases)."""
    counts = np.zeros(2 * n + 1)
    for r, p_now, p_prev in itertools.product(range(n), repeat=3):
        age = r - p_now if p_now < r else n + r - p_prev
        counts[:age] += 1.0                                   # age > a for a = 0..age-1
    return counts / n ** 3


def simulated_ages(idx, n, burn):
    """Counts of the ages of all (entry, iteration) pairs for the iterations t >= burn of the stream idx (batch one):
    array h with h[a] = number of pairs of age a. Every entry must have been refreshed before `burn`."""
    T = idx.size
    order = np.argsort(idx, kind="stable")                    # refresh times, entry by entry, increasing
    ent = idx[order]
    start = order                                             # s: a refresh of the entry
    nxt = np.empty_like(order)                                # next refresh of the same entry (T - 1 if none: the
    nxt[:-1] = np.where(ent[1:] == ent[:-1], order[1:], T - 1)  # entry is read with ages up to T - 1 - s)
    nxt[-1] = T - 1
    first = np.full(n, T)
    first[idx[::-1]] = np.arange(T)[::-1]
    if first.max() >= burn:
        raise SystemExit("an entry is not refreshed before the burn-in: lengthen it")
    lo = np.maximum(start + 1, burn) - start                  # ages at the iterations t in (s, next], t >= burn
    hi = nxt - start
    keep = hi >= lo
    h = np.zeros(T + 2)
    np.add.at(h, lo[keep], 1.0)
    np.add.at(h, hi[keep] + 1, -1.0)
    h = np.cumsum(h)[:T + 1]
    if abs(h.sum() - n * (T - burn)) > 0.5:
        raise SystemExit("the simulated ages do not cover every (entry, iteration) pair")
    return h


def initial_left(idx, n, passes):
    """Share of the entries never refreshed after p = 0..passes passes of the stream idx."""
    first = np.full(n, idx.size + 1)
    first[idx[::-1]] = np.arange(idx.size)[::-1]
    return np.array([(first >= p * n).mean() for p in range(passes + 1)])


def data():
    D = {}
    # (a) the two rasters
    for order in ("iid", "rr"):
        idx = stream(N_A, PASSES_A, order, SEED_A)
        per_pass = idx.reshape(PASSES_A, N_A)
        untouched = [np.setdiff1d(np.arange(N_A), row) for row in per_pass]
        times = [np.flatnonzero(idx == i) for i in range(N_A)]
        waits = np.concatenate([np.diff(t) for t in times if t.size > 1])
        D[f"a_{order}"] = {"idx": idx, "untouched": untouched, "longest_wait": int(waits.max())}
    D["a_expected_untouched"] = N_A * (1.0 - 1.0 / N_A) ** N_A

    # (b) the laws of the age, exact at n = N, and their checks
    ages = np.arange(0, int(U_MAX * N) + 1)
    D["ages"] = ages
    D["u"] = ages / N
    for order in ("iid", "rr", "cyclic"):
        D[f"S_{order}"] = age_survival(N, order, ages)
    n_small = 6
    D["enum_dev"] = float(np.abs(rr_enumeration(n_small) - age_survival(n_small, "rr", np.arange(2 * n_small + 1))).max())
    D["limit_dev"] = float(np.abs(D["S_rr"] - rr_limit(D["u"])).max())
    D["sim"] = {}
    for order in ("iid", "rr", "cyclic"):
        idx = stream(N, SIM_PASSES, order, SIM_SEED)
        h = simulated_ages(idx, N, SIM_BURN * N)
        surv = 1.0 - np.cumsum(h) / h.sum()                   # P(age > a), a = 0, 1, ...
        dev = float(np.abs(surv[:ages.size] - D[f"S_{order}"]).max())
        left = initial_left(idx, N, P_MAX)
        D["sim"][order] = {"dev": dev, "max_age": int(np.flatnonzero(h > 0).max()), "left": left}

    # the memory factor (the dot of panel (b)) and the share of the initial table (printed only)
    D["left_iid_passes"] = (1.0 - B / N) ** (np.arange(P_MAX + 1) * N / B)
    D["memory_factor"] = float((1.0 - B / N) ** (N / B))
    D["bound_cyclic"] = N // B                                # iterations
    D["bound_rr"] = 2 * N // B - 1
    return D


def check(D):
    if D["enum_dev"] > 1e-12:
        raise SystemExit(f"permutation law: the formula and the enumeration differ by {D['enum_dev']:.2e}")
    if D["limit_dev"] > 2.0 / N:
        raise SystemExit(f"permutation law: finite n and limit differ by {D['limit_dev']:.2e} (> 2/n)")
    for order, s in D["sim"].items():
        if s["dev"] > TOL_SIM:
            raise SystemExit(f"{order}: simulated and exact age laws differ by {s['dev']:.2e}")
    if D["sim"]["cyclic"]["max_age"] != D["bound_cyclic"] or D["sim"]["rr"]["max_age"] > D["bound_rr"]:
        raise SystemExit("a simulated age exceeds a sure bound of Proposition 5(b)")
    exact = {"iid": D["left_iid_passes"], "rr": np.clip(1.0 - np.arange(P_MAX + 1.0), 0.0, None)}
    exact["cyclic"] = exact["rr"]
    for order, s in D["sim"].items():
        tol = 0.05 if order == "iid" else 0.0                # one run of n = 1000 entries: binomial fluctuations
        if np.abs(s["left"] - exact[order]).max() > tol:
            raise SystemExit(f"{order}: simulated share of the initial table off the count")


def print_all(D):
    print(f"(a) n = {N_A}, b = 1, {PASSES_A} passes, seed {SEED_A} (index streams of vrlab.algorithms)")
    for order, name in (("iid", "independent"), ("rr", "permutation")):
        a = D[f"a_{order}"]
        print(f"    {name:11s}: entries untouched by each pass: {[len(x) for x in a['untouched']]} of {N_A}; longest "
              f"wait between two refreshes of an entry in the draw: {a['longest_wait']} iterations")
    print(f"    expected number of entries untouched by a pass, independent: n (1 - 1/n)^n = "
          f"{D['a_expected_untouched']:.2f}; sure bounds on the age: cyclic {N_A}, permutation {2 * N_A - 1} iterations")
    print(f"(b) n = {N}, b = {B}: P(age > u) at u = 0.5, 1, 1.5, 2, 3, 5, 7 passes")
    sel = [int(x * N) for x in (0.5, 1.0, 1.5, 2.0, 3.0, 5.0, 7.0)]
    for order, name in (("iid", "independent"), ("rr", "permutation"), ("cyclic", "cyclic")):
        print(f"    {name:11s}: " + ", ".join(f"{D[f'S_{order}'][k]:.3e}" for k in sel))
    print(f"    permutation, limit n -> infinity (1 - u + u^3/6, (2 - u)^3/6): "
          + ", ".join(f"{float(rr_limit(k / N)):.3e}" for k in sel))
    print(f"    sure bounds (Proposition 5(b)): cyclic {D['bound_cyclic']} iterations = {D['bound_cyclic'] * B / N:g} pass, "
          f"permutation {D['bound_rr']} iterations = {D['bound_rr'] * B / N:g} passes")
    print(f"    checks: formula against the enumeration (n = 6): {D['enum_dev']:.1e}; finite n against the limit: "
          f"{D['limit_dev']:.2e} (2/n = {2.0 / N:.1e})")
    for order, name in (("iid", "independent"), ("rr", "permutation"), ("cyclic", "cyclic")):
        s = D["sim"][order]
        print(f"    index stream '{order}', {SIM_PASSES} passes after {SIM_BURN} of burn-in: max |simulated - exact| of "
              f"P(age > u), u <= {U_MAX:g}: {s['dev']:.2e}; largest age {s['max_age']} iterations "
              f"({s['max_age'] / N:.3f} passes)")
    print(f"not drawn: share of the initial table after p = 0..{P_MAX} passes, n = {N}")
    print("    independent, expected (1 - 1/n)^(p n): " + ", ".join(f"{v:.4f}" for v in D["left_iid_passes"])
          + f"; memory factor (1 - b/n)^(n/b) = {D['memory_factor']:.4f}, 1/e = {np.exp(-1.0):.4f}")
    for order in ("iid", "rr", "cyclic"):
        print(f"    index stream '{order}', one run: " + ", ".join(f"{v:.3f}" for v in D["sim"][order]["left"]))


