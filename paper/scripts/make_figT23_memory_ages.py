def raster(ax, a, colour, bar_colour, ink):
    """Marks at (iteration, entry) and, behind them, bars over the passes that leave an entry untouched. A mark is
    MARK_W iterations wide, centred on its iteration, so that it stays visible on a slide."""
    from matplotlib.collections import PolyCollection
    bars = []
    for k, rows in enumerate(a["untouched"]):
        for i in rows:
            bars.append([(k * N_A, i + 0.5), ((k + 1) * N_A, i + 0.5), ((k + 1) * N_A, i + 1.5), (k * N_A, i + 1.5)])
    out = []
    if bars:
        out.append(ax.add_collection(PolyCollection(bars, facecolors=bar_colour, edgecolors="none", zorder=1)))
    h = 0.5 * MARK_W
    marks = [[(t + 0.5 - h, i + 0.5), (t + 0.5 + h, i + 0.5), (t + 0.5 + h, i + 1.5), (t + 0.5 - h, i + 1.5)]
             for t, i in enumerate(a["idx"])]
    out.append(ax.add_collection(PolyCollection(marks, facecolors=colour, edgecolors="none", zorder=3)))
    for k in range(1, PASSES_A):
        ax.axvline(k * N_A, color=ink["secondary"], lw=0.7, zorder=2)
    ax.set_xlim(0, PASSES_A * N_A)
    ax.set_ylim(0.5, N_A + 0.5)
    ax.set_yticks([1, N_A])
    ax.set_xticks([k * N_A for k in range(PASSES_A + 1)])
    ax.grid(visible=False)
    ax.set_ylabel("entry", labelpad=-6)
    return out


def draw(D):
    ps = es.setup("talk")
    ink = ps.INK
    IID, RR, CYC = ps.BLUE, ps.ORANGE, ps.AQUA     # independent sampling; fresh permutation per pass; fixed cyclic order
    bar = es.tint(ink["secondary"], 0.24)
    fig = es.figure("talk", height=2.75)
    fig.get_layout_engine().set(w_pad=0.03, wspace=0.04, h_pad=0.02, hspace=0.07)
    gs = fig.add_gridspec(2, 2, width_ratios=(1.0, 1.0))
    ax_i = fig.add_subplot(gs[0, 0])
    ax_p = fig.add_subplot(gs[1, 0], sharex=ax_i)
    ax_b = fig.add_subplot(gs[:, 1])
    b = es.Build()
    strip = dict(xycoords="axes fraction", textcoords="offset points", xytext=(0, 3), ha="left", va="bottom",
                 fontsize=es.small(), color=ink["secondary"])

    # (a) the two rasters
    raster(ax_i, D["a_iid"], IID, bar, ink)
    ax_i.tick_params(labelbottom=False)
    ax_i.set_title(f"(a) refreshed entries, n = {N_A}", loc="left", pad=17)
    ax_i.annotate("independent; grey: skipped by the pass", (0.0, 1.0), **strip).set_in_layout(False)
    marks_p = raster(ax_p, D["a_rr"], RR, bar, ink)
    ax_p.set_xlabel(f"iteration (one pass = {N_A})")
    lab_p = ax_p.annotate("a fresh permutation per pass", (0.0, 1.0), **strip)
    lab_p.set_in_layout(False)
    b.add(2, marks_p, lab_p)

    # (b) the law of the age
    u = D["u"]
    series = (("iid", IID, "independent: unbounded"), ("rr", RR, r"permutation: $u \leq 2 - b/n$"),
              ("cyclic", CYC, r"cyclic: $u \leq 1$"))
    for order, colour, text in series:
        S = D[f"S_{order}"]
        ax_b.plot(u[S > 0], S[S > 0], color=colour, lw=2.0, zorder=4, label=text)
    for x in (D["bound_cyclic"] * B / N, D["bound_rr"] * B / N):
        ax_b.axvline(x, color=ink["primary"], lw=0.8, ls=(0, (3.0, 2.0)), zorder=2)
    mf = D["memory_factor"]
    ax_b.plot([0.0, 1.0], [mf, mf], color=ink["secondary"], lw=0.8, zorder=3)
    ax_b.plot([1.0], [mf], ls="", marker="o", ms=6.5, mfc=IID, mec=ink["surface"], mew=1.2, zorder=6)
    ax_b.set_yscale("log")
    ax_b.set_ylim(1e-3, 1.5)
    ax_b.set_xlim(0, U_MAX)
    ax_b.set_xticks([0, 1, 2, 3, 4, 5, 6, 7])
    ax_b.set_yticks([1e-3, 1e-2, 1e-1, float(np.exp(-1.0)), 1.0])       # the dot is at mf = 0.3677, 1/e = 0.3679
    ax_b.set_yticklabels(["$10^{-3}$", "$10^{-2}$", "$10^{-1}$", "$1/e$", "$1$"])
    ax_b.minorticks_off()
    ax_b.set_xlabel("age $u$ (passes since refresh)")
    ax_b.set_ylabel(r"$P(\mathrm{age} > u)$")
    es.panel_title(ax_b, "(b) age of an entry")
    ax_b.set_title(ax_b.get_title(loc="left"), loc="left", pad=17)      # same height as the title of (a)
    # opaque legend: the dashed bound at u = 2 - b/n passes under it instead of through its handles
    b.legend(ax_b, loc="upper right", handlelength=0.9, borderaxespad=0.0, handletextpad=0.4, labelspacing=0.25,
             frameon=True, framealpha=1.0, facecolor=ink["surface"], edgecolor="none", borderpad=0.2)
    b.add(3, ax_b)
    es.save(fig, NAME, "talk", build=b,
            note=(f"$b = 1$; (a) one draw; (b) $n = {N}$. Counting facts (proved): they bound the memory, not the "
                  "speed"))


def main():
    D = data()
    check(D)
    print_all(D)
    draw(D)


if __name__ == "__main__":
    main()
