"""Figure T23 of the lecture (paper/talk/figures/figT23_memory_ages): an entry of a SAGA table keeps its error until
it is refreshed, and the order of the indices decides how long that lasts. Explanatory figure, not in the paper. It
explains the age bounds of Proposition 5(b) of paper/paper_saga_to_muon.tex, the memory factor (1 - b/n)^(n/b) of
(M7) and the row "Memory" of Table 2.

Setting (pure counting: no loss, no step, no iterate). A table of n entries; at iteration t a batch B_t of b indices is
read and the entries of B_t are replaced. Three orders, generated by the index streams of the SAGA code of the project
(vrlab.algorithms._index_stream, b = 1):
    independent   "iid": one uniform index per iteration, with replacement;
    permutation   "rr": a fresh uniform permutation of {1..n} at every pass;
    cyclic        "cyclic": the same fixed order at every pass.
AGE (definition used here, the one of Proposition 5(b)): the age at iteration t of entry i is t - s, s < t the last
iteration at which i was refreshed; it is the age at which the entry is read by the estimator, at least 1. The law
shown is that of the age of a uniformly chosen entry at a uniformly chosen iteration of the stationary regime (every
entry has been refreshed at least once). It is NOT the law of the wait between two refreshes of the same entry (for a
permutation that wait is triangular on [0, 2] passes: P(wait > u) = 1 - u^2/2, then (2 - u)^2/2).

Panels:
  (a) raster for a small table, n = 30, b = 1, four passes, one draw (seed 0): a mark at (t, i) when entry i is
      refreshed at iteration t (drawn 1.5 iterations wide to stay visible on a slide). Top strip: independent indices;
      grey bars: the entries that a whole pass leaves untouched. Bottom strip: a fresh permutation per pass (every
      entry exactly once per pass: no grey bar).
  (b) P(age > u) against u in passes (n iterations), n = 1000, b = 1, exact at this n (u n = a iterations):
        independent   (1 - 1/n)^a, about e^-u: no sure bound; at u = 1 it is the memory factor (1 - b/n)^(n/b) of
                      (M7), 0.3677, about 1/e (dot and tick "1/e"): the share of the table that a pass leaves untouched;
        cyclic        1 - a/n for a <= n: at most n iterations = 1 pass;
        permutation   (1/n) sum_{r=0}^{n-1} [ max(r - a, 0)/n + ((n - r)/n) clip(n + r - a, 0, n)/n ]
                      (r: position of the iteration in its pass; first term: the entry was refreshed earlier in the
                      same pass; second: it was not, and its age is counted from its position in the previous pass);
                      as n -> infinity: 1 - u + u^3/6 for u <= 1 and (2 - u)^3/6 for 1 <= u <= 2; at most 2n - 1
                      iterations = 2 - 1/n passes.
      For a batch b dividing n the same laws hold with n/b batches in the place of n indices: at most n/b iterations
      (cyclic) and 2n/b - 1 (permutation), i.e. 1 and 2 - b/n passes, the bounds of Proposition 5(b) (dashed lines).
Not drawn, printed only (a third panel made the slide too dense, and under independent sampling it repeats the curve
of (b)): the share of the INITIAL table still present after p passes, n = 1000, b = 1: independent, expected share
(1 - 1/n)^(p n); permutation and cyclic: exactly 1 - p during the first pass, nothing left after it.

Status. Everything is a counting fact (proved). Checks done by the script, which stops if one fails: the permutation
law against an enumeration of all positions for n = 6 and against its limit; the three laws and the three shares of
the initial table against the index streams of the SAGA code (n = 1000, SIM_PASSES passes, seed SIM_SEED); the largest
simulated age against the two sure bounds. The figure is about ages only: these counts bound the memory of the table,
they are not the rate of a run (figures T24, T24b), and they do not by themselves explain the passes saved by a
permutation in (M7).

Progressive build (states s1-s3): s1 the raster under independent sampling; s2 the raster under a fresh permutation;
s3 panel (b).

The script prints every number it plots. Nothing is read from the results of the project.
Run:    OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 python paper/scripts/make_figT23_memory_ages.py
Output: paper/talk/figures/figT23_memory_ages.pdf and .png, and the states _s1 ... _s3
"""
from __future__ import annotations

import itertools
import os
import sys

